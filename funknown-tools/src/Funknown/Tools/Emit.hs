{-# LANGUAGE Safe #-}
-- | What every generated module shares: the GENERATED header, identifiers
-- built from registry text, and the vendor deny-list check on them.
module Funknown.Tools.Emit
  ( Source (..)
  , header
  , pascal
  , segments
  , denied
  , checkIdentifiers
  , hsString
  ) where

import Data.Char (isAlphaNum, isDigit, isLower, isUpper, toUpper)
import Data.List (tails)

-- | A vendored file a module was generated from, by its path from the repo
-- root and the sha256 of its bytes.
data Source = Source {srcPath :: FilePath, srcSha256 :: String}

header :: String -> [Source] -> [String]
header what srcs =
  ["-- GENERATED by gen-vocab (funknown-tools) from " ++ what ++ ". Do not edit."]
    ++ ["--   " ++ srcPath s ++ "  sha256 " ++ srcSha256 s | s <- srcs]
    ++ ["-- Regenerate with: cabal run gen-vocab -- --repo ."]

-- | Words of registry text, each capitalised and joined:
-- "Non-Authoritative Information" -> "NonAuthoritativeInformation",
-- "sha-512" -> "Sha512".
pascal :: String -> String
pascal = concatMap cap . wordsBy (not . isAlphaNum)
  where
    cap (c : cs) = toUpper c : cs
    cap [] = []

wordsBy :: (Char -> Bool) -> String -> [String]
wordsBy p s = case dropWhile p s of
  [] -> []
  s' -> let (w, r) = break p s' in w : wordsBy p r

-- | Split a token at case changes, underscores and hyphens, as check-vendor
-- does: "isS3Error" -> ["is","S3","Error"], "x-amz-meta" -> ["x","amz","meta"].
segments :: String -> [String]
segments = concatMap caseSplit . wordsBy (`elem` "_-")
  where
    caseSplit [] = []
    caseSplit (c : cs)
      | isUpper c =
          let (ups, rest) = span (\x -> isUpper x || isDigit x) (c : cs)
           in case rest of
                (l : _) | isLower l && length ups > 1 -> init ups : caseSplit (last ups : rest)
                _ -> let (low, rest') = span (\x -> isLower x || isDigit x) rest in (ups ++ low) : caseSplit rest'
      | otherwise = let (w, rest) = span (\x -> isLower x || isDigit x) (c : cs) in w : caseSplit rest

-- | The fixed half of the design's deny-list: spellings only a vendor uses.
-- The other half comes from the adapter's S3Call type, which doesn't exist yet.
denyList :: [String]
denyList =
  [ "S3", "AWS", "Aws", "amz", "Smithy", "Multipart", "MpuObjectSize", "PartNumber", "FULL_OBJECT"
  , "COMPOSITE", "ChecksumCRC64NVME", "NoSuchUpload", "NoSuchKey", "SlowDown", "Lifecycle"
  ]

-- | Does an entry equal a run of consecutive segments of the token?
denied :: String -> [String]
denied tok = [e | e <- denyList, segments e `isRun` segments tok]
  where
    isRun needle hay = any (needle `isPrefixOfList`) (tails hay)
    isPrefixOfList a b = take (length a) b == a && not (null a)

checkIdentifiers :: [String] -> Either String ()
checkIdentifiers ids = case [(i, d) | i <- ids, d <- denied i] of
  [] -> Right ()
  hits -> Left ("deny-list matched generated identifiers: " ++ show hits)

-- | A Haskell string literal for ASCII registry text; anything else is refused
-- so a generated module stays plain ASCII.
hsString :: String -> Either String String
hsString s
  | all (\c -> c >= ' ' && c <= '~') s = Right (show s)
  | otherwise = Left ("non-ASCII or control character in " ++ show s)
